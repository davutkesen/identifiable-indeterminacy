def fetch(url):
    with urllib.request.urlopen(url, timeout=120) as r:
        return r.read()


def load_dataset(name, manifest):
    """Download (once) and verify one PMLB dataset; return a DataFrame."""
    os.makedirs(CACHE, exist_ok=True)
    path = os.path.join(CACHE, name + ".tsv.gz")
    if not os.path.exists(path):
        ptr = fetch(POINTER.format(name)).decode()
        oid = [l.split(":")[1] for l in ptr.splitlines() if l.startswith("oid")][0]
        blob = fetch(MEDIA.format(name))
        if hashlib.sha256(blob).hexdigest() != oid:
            raise RuntimeError(f"{name}: SHA-256 does not match the LFS pointer")
        with open(path, "wb") as f:
            f.write(blob)
    blob = open(path, "rb").read()
    manifest[name] = hashlib.sha256(blob).hexdigest()
    return pd.read_csv(io.BytesIO(gzip.decompress(blob)), sep="\t")


def select(summary):
    """Steps 1-5 of the selection rule; returns the kept names and the reason
    every other classification dataset was dropped."""
    c = summary[summary.task == "classification"]
    kept, dropped = [], {}
    drop_same = {g2: g[0] for g in SAME_SAMPLE for g2 in sorted(g)[1:]}
    for name in sorted(c.dataset):
        if name.startswith("_deprecated_"):
            dropped[name] = "deprecated duplicate"
        elif name in GENERATED:
            dropped[name] = "generated: " + GENERATED[name]
        elif name in USED_IN_B:
            dropped[name] = "already used in source B"
        elif name in drop_same:
            dropped[name] = f"same sample as {sorted([g for g in SAME_SAMPLE if name in g][0])[0]}"
        else:
            kept.append(name)
    return kept, dropped


def make_task(df):
    """Steps 6 and 7: binary target, complete cases, size rule, stratified
    subsample."""
    y_raw = df["target"].values
    X = df.drop(columns=["target"]).values.astype(np.float64)
    complete = np.isfinite(X).all(1)
    X, y_raw = X[complete], y_raw[complete]
    if len(y_raw) == 0:
        return None, None, {"n_full": int(len(complete)), "n_complete": 0}
    labels, counts = np.unique(y_raw, return_counts=True)
    share = counts / counts.sum()
    if len(labels) == 2:
        pos = labels[np.argmin(counts)]
    else:
        pos = labels[np.argmin(np.abs(share - 0.20))]
    y = (y_raw == pos).astype(int)
    info = {"n_full": int(len(complete)), "n_complete": int(len(y)),
            "classes": int(len(labels)), "positive_label": str(pos)}
    if len(y) < 200 or y.sum() < 40:
        return None, None, info
    if len(y) > NMAX:
        X, _, y, _ = train_test_split(X, y, train_size=NMAX, stratify=y,
                                      random_state=SEED)
    return X, y, info


def main():
    from exp4b_regime_crossfit import point, summarise
    summary = pd.read_csv(io.BytesIO(fetch(SUMMARY)), sep="\t")
    kept, dropped = select(summary)
    print(f"{len(kept)} datasets pass steps 1-5; {len(dropped)} dropped", flush=True)
    manifest, pts, too_small = {}, [], {}
    for name in kept:
        df = load_dataset(name, manifest)
        X, y, info = make_task(df)
        if X is None:
            too_small[name] = info
            continue
        p = point(X, y, name)
        if p is None:
            too_small[name] = info
            continue
        p.update(info)
        p["source"] = "D independent real (PMLB)"
        pts.append(p)
        print(f"  {name:36s} n={p['n']:5d} d={p['d']:4d} pos={p['pos_rate']:.2f}  "
              f"x={p['crossfit_tuned']['x']:+.3f} y={p['crossfit_tuned']['y']:+.3f}",
              flush=True)
    out = {"selection": {"kept": [p["task"] for p in pts],
                         "dropped_steps_1_to_5": dropped,
                         "dropped_size_rule": too_small},
           "points": pts, "summary": {}}
    for key in ("coupled", "crossfit", "coupled_tuned", "crossfit_tuned"):
        s = summarise(pts, key)
        out["summary"][key] = s
        print(f"{key:15s} n={s['n']:3d} rho={s['rho']:+.3f} "
              f"CI[{s['ci95'][0]:+.3f},{s['ci95'][1]:+.3f}]", flush=True)
    json.dump(manifest, open("pmlb_manifest.json", "w"), indent=1, sort_keys=True)
    json.dump(out, open("regime_pmlb.json", "w"), indent=1)
    print("written regime_pmlb.json and pmlb_manifest.json")


if __name__ == "__main__":
    main()
