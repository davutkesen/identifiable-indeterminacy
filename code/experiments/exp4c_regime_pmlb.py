"""Independent real tasks for the regime relation (source D).

The regime relation of exp4/exp4b was measured on 133 tasks, of which only
24 were independent real tasks, and all of those lay in the region where the
transformation is predicted to hurt.  This script tests the relation on a
further collection of independent real tasks: the classification datasets of
the Penn Machine Learning Benchmarks (PMLB; Olson et al. 2017, Romano et al.
2022), selected by the rule below, which was fixed in this file before any
of the datasets was evaluated and has not been changed since.

Selection rule
  1. PMLB classification datasets (all_summary_stats.tsv, task ==
     "classification").
  2. Exclude PMLB's deprecated duplicates (names beginning "_deprecated_").
  3. Exclude datasets whose instances were generated by a program: by
     simulation, by random distortion, or by enumerating a rule or a game
     (GENERATED below, with the reason for each).
  4. Exclude datasets already used in source B: iris, wine, the Wisconsin
     diagnostic breast-cancer data, and optdigits, of which the digits data
     of scikit-learn is a part.
  5. Keep one dataset per underlying sample where PMLB holds several feature
     sets or several targets for the same instances (SAME_SAMPLE below; the
     first name in alphabetical order is kept).
  6. Binary datasets: the minority class is positive.  Multiclass datasets:
     the class whose share is closest to 0.20 is positive and all others are
     negative (ties: the smaller class label).
  7. Remove every instance with a missing feature value (complete cases),
     then keep the task if it has at least 200 instances and at least 40
     positives.  Tasks with more than 2500 instances are subsampled to 2500,
     stratified, with a fixed seed (2500 is also the size used for source A).

Every task is evaluated exactly as in exp4b_regime_crossfit.point: three
stratified 75/25 splits, the held-out part divided into two stratified
halves, x on the first half and y on the second; once untuned (k = 5,
uniform weights) and once with both arms tuned by five-fold cross-validation
on the training part (k for the plain rule; the weight simplex and k for the
proposed construction); class weighting off on both sides.

The datasets are downloaded from the PMLB repository and verified against
the SHA-256 digest that the repository's Git LFS pointer records; the
digests are written to pmlb_manifest.json so that the exact files can be
identified later.
"""
